from datetime import datetime
from typing import Literal
from pydantic import BaseModel

# Defining string types (enums) using Literal
TicketStatus = Literal['open', 'in_progress', 'resolved', 'closed']
TicketPriority = Literal['low', 'medium', 'high', 'critical']
TicketCategory = Literal['bug', 'feature', 'billing', 'support', 'other']


# Replicate TS interface as a Pydantic Model
class Ticket(BaseModel):
    id: str
    title: str
    description: str
    
    # Reuse your string literal types
    status: TicketStatus
    priority: TicketPriority | None  = None # The "| None" means it is optional/nullable
    category: TicketCategory | None = None

    # Generated by AI worker
    ai_summary: str | None = None
    ai_category: TicketCategory | None = None
    ai_priority: TicketPriority | None = None
    ai_processed: bool

    creator_id: str
    assignee_id: str | None = None
    
    # Use standard datetime objects instead of generic strings for better validation
    created_at: datetime 
    updated_at: datetime

     # 🔥 CRITICAL: Add this for SQLAlchemy compatibility
    # model_config = {"from_attributes": True}


class TicketListResponse(BaseModel):
    tickets: list[Ticket]
    total: int
    page: int
    page_size: int


class CreateTicketPayload(BaseModel):
    title: str
    description: str
    priority: TicketPriority | None
    category: TicketCategory | None